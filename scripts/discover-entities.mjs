// Discover entities by scanning src/entities/*/entity.js
// and generating src/entities/entity-manifest.js.
// Also discovers image assets in src/img/entities/<entity>/.
//
// Usage:
//   node scripts/discover-entities.mjs
//
// This is a build-time helper. The generated manifest is also
// committed so the app works without running the script.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const entitiesDir = path.join(__dirname, '..', 'src', 'entities');
const imgEntitiesDir = path.join(__dirname, '..', 'src', 'img', 'entities');
const manifestPath = path.join(entitiesDir, 'entity-manifest.js');

const SUPPORTED_EXTENSIONS = new Set([
    '.png', '.jpg', '.jpeg', '.gif', '.webp', '.bmp', '.svg',
]);

function isImageFile(filename) {
    const ext = filename.toLowerCase().match(/\.[^.]+$/)?.[0] || '';
    return SUPPORTED_EXTENSIONS.has(ext);
}

function discoverEntityAssets(entityName) {
    const spriteDir = path.join(imgEntitiesDir, entityName);
    if (!fs.existsSync(spriteDir)) {
        return [];
    }

    return discoverAssetsFromDir(spriteDir, `./img/entities/${entityName}`);
}

function discoverAssetsFromDir(dir, assetPath) {
    const components = [];
    const files = fs.readdirSync(dir).sort();
    // Deterministic default layer ordering: filesystem order.
    // Lowest layer = drawn first (behind), highest layer = drawn last (in front).
    // Each component gets an incrementing default so they never collide.
    for (let i = 0; i < files.length; i++) {
        const file = files[i];
        if (isImageFile(file)) {
            const ext = file.toLowerCase().match(/\.[^.]+$/)?.[0] || '';
            const name = ext ? file.slice(0, -ext.length) : file;
            components.push({
                id: name,
                label: name,
                spritePath: `${assetPath}/${file}`,
                defaultWidth: 0,
                defaultHeight: 0,
                defaultOffsetX: 0,
                defaultOffsetY: 0,
                defaultScale: 1.0,
                defaultLayer: i * 10,
            });
        }
    }
    return components;
}

function writeSpriteComponents(entityDir, entityName, components) {
    const spriteComponentsPath = path.join(entityDir, 'sprite-components.js');
    const content = `// Generated by scripts/discover-entities.mjs
// Do not edit manually. Add/remove images in src/img/entities/${entityName}/
// and rerun the script to update this file.

export const SPRITE_COMPONENTS = ${JSON.stringify(components, null, 4)};
`;
    fs.writeFileSync(spriteComponentsPath, content, 'utf8');
}

function main() {
    if (!fs.existsSync(entitiesDir)) {
        console.error(`Entities directory not found: ${entitiesDir}`);
        process.exit(1);
    }

    const entries = fs.readdirSync(entitiesDir, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => entry.name)
        .sort();

    const imports = [];
    const descriptors = [];

    for (const dir of entries) {
        const entityFile = path.join(entitiesDir, dir, 'entity.js');
        if (!fs.existsSync(entityFile)) {
            continue;
        }

        // Each entity.js must export a DESCRIPTOR object
        const importName = `entity_${dir.replace(/[^a-zA-Z0-9]/g, '_')}`;
        imports.push(`import { DESCRIPTOR as ${importName} } from './${dir}/entity.js';`);

        // Discover image assets for this entity
        const entityDir = path.join(entitiesDir, dir);
        const assets = discoverEntityAssets(dir);

        // Generate sprite-components.js for the entity
        writeSpriteComponents(entityDir, dir, assets);

        // Use discovered assets if found, otherwise fall back to descriptor's spriteComponents
        const spriteComponents = assets.length > 0 ? assets : `${importName}.spriteComponents || []`;

        descriptors.push(`    {
        ...${importName},
        spriteComponents: ${typeof spriteComponents === 'string' ? spriteComponents : JSON.stringify(spriteComponents, null, 8).replace(/^/gm, '        ').trim()},
    }`);
    }

    const content = `// Entity Manifest
// Central list of all registered game entities and their
// implementation modules.
//
// Generated by scripts/discover-entities.mjs on ${new Date().toISOString()}
//
// Following STANDARDISATION.md: this is the single source of truth
// for entity metadata.

${imports.join('\n')}

export const ENTITY_MANIFEST = [
${descriptors.join(',\n')},
];
`;

    fs.writeFileSync(manifestPath, content, 'utf8');
    console.log(`Generated ${manifestPath} with ${descriptors.length} entities:`);
    for (const dir of entries) {
        const entityFile = path.join(entitiesDir, dir, 'entity.js');
        if (fs.existsSync(entityFile)) {
            const spriteDir = path.join(imgEntitiesDir, dir);
            const assetCount = fs.existsSync(spriteDir) ? fs.readdirSync(spriteDir).filter(isImageFile).length : 0;
            console.log(`  - ${dir} (${assetCount} assets)`);
        }
    }
}

main();
